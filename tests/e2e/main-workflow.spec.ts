import { test, expect } from "@playwright/test";
import { gotoStage, waitForDemoMedia } from "./helpers";

test("footage → draft → render → approve → plan", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Your next story/ })).toBeVisible();
  await waitForDemoMedia(page);

  // Create a Reel from two library clips
  await page.getByRole("link", { name: "Create Reel" }).first().click();
  await expect(page).toHaveURL(/\/create$/);
  await page.getByPlaceholder("Title (optional)").fill("E2E Morning pour");
  const picker = page.getByRole("region").or(page.locator("section")).filter({ hasText: "New Reel" }).first();
  await picker.getByRole("button", { name: /C004_kettle_pour/ }).click();
  await picker.getByRole("button", { name: /C007_ice_glass/ }).click();
  await page.getByRole("button", { name: /Create with 2 clips/ }).click();
  await expect(page).toHaveURL(/\/create\/prj_/);
  await expect(page.getByLabel("Reel title")).toHaveValue("E2E Morning pour");

  // Trim with buttons (no drag), reorder with arrows
  await gotoStage(page, "Footage");
  await page.getByRole("button", { name: "Start (s): forward 0.5 seconds" }).click();
  await page.getByRole("button", { name: /Move C007_ice_glass.mp4 earlier/ }).first().click();
  await expect(page.getByText("Saved", { exact: true })).toBeVisible();

  // Brief → demo draft (clearly labelled as not Claude)
  await gotoStage(page, "Creative brief");
  await page.getByLabel("Featured product").selectOption({ label: "House Blend · Balena product" });
  await page.getByRole("button", { name: /Draft \(demo template\)/ }).click();
  await gotoStage(page, "Thai copy");
  await expect(page.getByText(/DEMO template draft — not generated by Claude/)).toBeVisible({ timeout: 60_000 });
  await expect(page.getByLabel("Thai caption")).not.toHaveValue("");

  // Edit a subtitle in Thai
  const firstCue = page.getByLabel("Subtitle 1 text");
  await firstCue.fill("กาแฟดริปยามเช้า ☕");
  await expect(page.getByText("Saved", { exact: true })).toBeVisible();

  // Render & send for review
  await gotoStage(page, "Review");
  await page.getByRole("button", { name: /Send for review/ }).click();
  await expect(page.getByText(/Render v1 queued/)).toBeVisible();

  const id = page.url().split("/").pop()!;
  await page.goto(`/review/${id}`);
  const approve = page.getByRole("button", { name: "Approve draft" });
  await expect(approve).toBeEnabled({ timeout: 120_000 });
  await expect(page.getByText("Demo stand-in")).toHaveCount(0); // real FFmpeg render
  await approve.click();
  await expect(page.getByText("Approved for this version")).toBeVisible();

  // Plan publishing (local plan, clearly distinguished from Meta)
  await page.getByRole("link", { name: "Plan publishing" }).click();
  const dialog = page.getByRole("dialog", { name: "New publishing plan" });
  await expect(dialog).toBeVisible();
  await dialog.getByLabel("Date", { exact: true }).fill("2026-12-24");
  await dialog.getByLabel("Time", { exact: true }).fill("10:30");
  await expect(dialog.getByText(/Bangkok \(GMT\+7\)/)).toBeVisible();
  await dialog.getByRole("button", { name: "Create plan" }).click();
  await expect(page.getByText("Plan created")).toBeVisible();

  await page.goto("/calendar?view=agenda&d=2026-12-20");
  await expect(page.getByRole("heading", { name: /Thursday 24 December/ })).toBeVisible();
  const row = page.getByRole("button", { name: /E2E Morning pour/ });
  await expect(row).toContainText("10:30");
  await expect(row).toContainText("Planned · local");
});
