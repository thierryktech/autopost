import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { asc, eq } from "drizzle-orm";
import { getDb } from "../../db/connect";
import { brandKit, clipEdits, footage, products, projects } from "../../db/schema";
import { claudeAdapter, driveAdapter, ffmpegAvailable } from "../../adapters";
import { saveDraft } from "../../services/projects";
import { logActivity } from "../../services/activity";
import type { JobHandler } from "../types";

/** Extracts 2 small keyframes per clip so Claude can "see" the footage (live mode only). */
async function keyframes(driveFileId: string, durationMs: number): Promise<Buffer[]> {
  if (!ffmpegAvailable()) return [];
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "balena-kf-"));
  try {
    const src = path.join(dir, "clip.mp4");
    await driveAdapter().downloadTo(driveFileId, src);
    const out: Buffer[] = [];
    for (const frac of [0.25, 0.7]) {
      const jpg = path.join(dir, `${frac}.jpg`);
      spawnSync("ffmpeg", ["-y", "-ss", String((durationMs * frac) / 1000), "-i", src, "-frames:v", "1", "-vf", "scale=384:-2", "-q:v", "5", jpg], { stdio: "ignore" });
      if (fs.existsSync(jpg)) out.push(fs.readFileSync(jpg));
    }
    return out;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

export const claudeDraftHandler: JobHandler = async (job) => {
  const projectId = String(job.payload.projectId);
  const db = await getDb();
  const [p] = await db.select().from(projects).where(eq(projects.id, projectId));
  if (!p) return { kind: "done", result: { skipped: "deleted" } };
  const clips = await db
    .select({ clip: clipEdits, footage })
    .from(clipEdits)
    .innerJoin(footage, eq(clipEdits.footageId, footage.id))
    .where(eq(clipEdits.projectId, projectId))
    .orderBy(asc(clipEdits.position));
  const [kit] = await db.select().from(brandKit).limit(1);
  const product = p.productId ? (await db.select().from(products).where(eq(products.id, p.productId)))[0] : undefined;
  const adapter = await claudeAdapter();
  const clipInputs = [];
  for (const c of clips) {
    if (c.footage.availability !== "available") continue;
    clipInputs.push({
      footageId: c.footage.id,
      name: c.footage.name,
      durationMs: c.footage.durationMs ?? 5000,
      keyframesJpeg: adapter.mode === "live" ? await keyframes(c.footage.driveFileId, c.footage.durationMs ?? 5000) : undefined,
    });
  }
  const draft = await adapter.draftEdit({
    brief: { purpose: p.brief.purpose, targetDurationSec: p.brief.targetDurationSec, style: p.brief.style, notes: p.brief.notes },
    clips: clipInputs,
    product: product ? { name: product.name, nameTh: product.nameTh, verifiedFacts: product.verifiedFacts, type: product.type } : null,
    brand: { toneOfVoice: kit?.toneOfVoice ?? "", defaultCtas: kit?.defaultCtas ?? [], prohibitedClaims: kit?.prohibitedClaims ?? [] },
  });
  await saveDraft(projectId, p.version, {
    clips: draft.clips,
    subtitles: draft.subtitles,
    captionTh: draft.captionTh,
  });
  const note =
    draft.generatedBy === "claude"
      ? `Drafted by Claude (${draft.model}). ${draft.rationale}`
      : `DEMO template draft — not generated by Claude. ${draft.rationale}`;
  await db.update(projects).set({ claudeDraftNote: note }).where(eq(projects.id, projectId));
  await logActivity({
    category: "editing",
    level: "success",
    title: `Edit draft ready: ${p.title}`,
    detail: note,
    projectId,
    jobId: job.id,
  });
  return { kind: "done", result: { generatedBy: draft.generatedBy } };
};
